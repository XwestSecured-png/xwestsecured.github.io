#!/usr/bin/env python3
"""Writes sql/02_seed_data.sql: deterministic synthetic clients (no real people)."""
import random
from datetime import date, timedelta
from pathlib import Path

random.seed(1102)
FIRST = ["Avery", "Jordan", "Riley", "Casey", "Morgan", "Quinn", "Rowan", "Sage", "Skyler", "Dakota", "Emerson",
         "Finley", "Harper", "Jamie", "Kendall", "Logan", "Micah", "Parker", "Reese", "Taylor"]
LAST = ["Adams", "Baker", "Carter", "Diaz", "Ellis", "Foster", "Garcia", "Hughes", "Irwin", "Jensen", "Kim", "Lopez",
        "Moore", "Nguyen", "Owens", "Patel", "Quintero", "Reyes", "Shaw", "Turner", "Usman", "Vega", "Ward", "Young"]
SITES = {1: ("Eastside Center", 150), 2: ("Westside Center", 120), 3: ("Mobile Outreach", 30)}
lines = ["-- Generated by generate_seed.py (synthetic data). Loaded as the DB owner BEFORE audit triggers exist.",
         "INSERT INTO app.sites VALUES " + ", ".join(f"({i}, '{n}')" for i, (n, _) in SITES.items()) + ";",
         "INSERT INTO app.staff VALUES (1,'alice_cw','Alice Romero',1,'Caseworker',true),"
         " (2,'bob_cw','Bob Chen',2,'Caseworker',true), (3,'mallory_cw','Mallory Price',2,'Caseworker',true);"]
cid, rows, svc = 1000, [], []
for site, (_, n) in SITES.items():
    for _ in range(n):
        cid += 1
        dob = date(1940, 1, 1) + timedelta(days=random.randint(0, 30000))
        phone = f"555-01{random.randint(0, 99):02d}"          # 555-01xx: reserved fictional numbers
        note = random.choice(["Requested food assistance", "Housing intake completed", "Referred to job training",
                              "Counseling follow-up scheduled", "Legal aid consultation"])
        rows.append(f"({cid}, {site}, '{random.choice(FIRST)}', '{random.choice(LAST)}', '{dob}', '{phone}', "
                    f"pgp_sym_encrypt('{note}', 'lab-only-notes-key', 'cipher-algo=aes256'), '2026-0{random.randint(1, 9)}-15')")
        for _ in range(random.randint(1, 3)):
            svc.append(f"({cid}, {site}, '2026-{random.randint(1, 10):02d}-{random.randint(1, 28):02d}', "
                       f"'{random.choice(['food', 'housing', 'counseling', 'job-training', 'legal-aid'])}')")
lines.append("INSERT INTO app.clients (client_id, site_id, first_name, last_name, date_of_birth, phone, notes_enc, created_at) VALUES\n  "
             + ",\n  ".join(rows) + ";")
lines.append("INSERT INTO app.services_provided (client_id, site_id, service_date, service_type) VALUES\n  " + ",\n  ".join(svc) + ";")
Path(__file__).with_name("02_seed_data.sql").write_text("\n".join(lines) + "\n")
print(f"[+] {cid - 1000} clients, {len(svc)} service records")
